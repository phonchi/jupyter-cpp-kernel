"""Generate maze_sprites.hpp: Pikachu / Snorlax / turtle cursor shapes for CTurtle.

Source images are the Python HW3 turtle shapes (HW3/02_FILE/Py/{pika,snor}.gif).
The same generated header is copied to the course kernel and to the HW3 C++ files.

Usage: python make_maze_sprites.py OUTPUT.hpp DIR_WITH_pika.gif_AND_snor.gif
"""
from pathlib import Path
import sys

from PIL import Image

PY_DIR = None  # directory holding pika.gif and snor.gif (HW3/02_FILE/Py), from argv
SPRITES = [('pikachu', 'pika.gif'), ('snorlax', 'snor.gif')]
# Python turtle's "turtle" polygon (Lib/turtle.py), head at +y. CTurtle shapes
# point toward -y (compare its "arrow"), so y is negated below.
PY_TURTLE = [(0, 16), (-2, 14), (-1, 10), (-4, 7), (-7, 9), (-9, 8), (-6, 5), (-7, 1),
             (-5, -3), (-8, -6), (-6, -8), (-4, -5), (0, -7), (4, -5), (6, -8), (8, -6),
             (5, -3), (7, 1), (6, 5), (9, 8), (7, 9), (4, 7), (1, 10), (2, 14)]


def rgba_bytes(path):
    with Image.open(path) as source:
        img = source.convert('RGBA')
    raw = img.tobytes()
    pixels = [tuple(raw[i:i + 4]) for i in range(0, len(raw), 4)]
    alpha = [p[3] for p in pixels]
    assert 0 in alpha and 255 in alpha, f'{path}: transparency was not preserved'
    assert set(alpha) <= {0, 255}, f'{path}: unexpected partial alpha'
    data = []
    for r, g, b, a in pixels:
        data += [r, g, b, a] if a else [0, 0, 0, 0]
    return img.size, data


def c_array(data, per_line=24):
    lines = []
    for i in range(0, len(data), per_line):
        lines.append('        ' + ','.join(f'0x{v:02x}' for v in data[i:i + per_line]) + ',')
    return '\n'.join(lines)


def main(out):
    parts = ['''// maze_sprites.hpp -- Pikachu / Snorlax / turtle cursor shapes for the CTurtle maze.
// GENERATED by make_maze_sprites.py from the Python HW3 images pika.gif and snor.gif.
// Include this header AFTER CTurtle.hpp. C++11.
//
//     maze_sprites::setShape(turtle, "pikachu");   // or "snorlax", "turtle", "arrow", ...
#ifndef MAZE_SPRITES_HPP
#define MAZE_SPRITES_HPP

#include <stdexcept>
#include <string>

namespace maze_sprites {

// A picture used as the turtle's shape. Like Python turtle's GIF shapes, it is
// centred on the turtle and never rotated; transparent pixels are not drawn.
class ImageShape : public cturtle::AbstractDrawableObject {
public:
    explicit ImageShape(const cturtle::Image& image) : image(&image) {}
    cturtle::AbstractDrawableObject* copy() const override { return new ImageShape(*this); }
    void draw(const cturtle::Transform& t, cturtle::Image& canvas) const override {
        const cturtle::Point centre = t.getTranslation();
        canvas.draw_image(centre.x - image->width() / 2, centre.y - image->height() / 2,
                          *image, image->get_shared_channel(3), 1, 255);
    }
private:
    const cturtle::Image* image;  // points to a function-local static below
};

namespace detail {
inline cturtle::Image makeImage(const unsigned char* rgba, int width, int height) {
    cturtle::Image image(width, height, 1, 4);
    for (int y = 0; y < height; ++y)
        for (int x = 0; x < width; ++x)
            for (int c = 0; c < 4; ++c)
                image(x, y, 0, c) = rgba[(y * width + x) * 4 + c];
    return image;
}
}  // namespace detail
''']
    for name, filename in SPRITES:
        (w, h), data = rgba_bytes(PY_DIR / filename)
        parts.append(f'''
// {filename}: {w}x{h} RGBA
inline const cturtle::Image& {name}Image() {{
    static const unsigned char rgba[{w} * {h} * 4] = {{
{c_array(data)}
    }};
    static const cturtle::Image image = detail::makeImage(rgba, {w}, {h});
    return image;
}}
''')
    turtle_points = ', '.join(f'{{{x}, {-y}}}' for x, y in PY_TURTLE)
    parts.append(f'''
// Python turtle's "turtle" polygon.
inline cturtle::Polygon turtlePolygon() {{
    return cturtle::Polygon{{{turtle_points}}};
}}

// Sets the turtle's shape: "pikachu", "snorlax", "turtle", or a CTurtle built-in
// shape ("arrow", "triangle", "square", "indented triangle").
inline void setShape(cturtle::Turtle& turtle, const std::string& name) {{
    if (name == "pikachu") turtle.shape(ImageShape(pikachuImage()));
    else if (name == "snorlax") turtle.shape(ImageShape(snorlaxImage()));
    else if (name == "turtle") turtle.shape(turtlePolygon());
    else if (name == "arrow" || name == "triangle" || name == "square" ||
             name == "indented triangle") turtle.shape(name);
    else throw std::invalid_argument("Unknown turtle shape \\"" + name + "\\". Use \\"pikachu\\", "
                                     "\\"snorlax\\", \\"turtle\\", \\"arrow\\", \\"triangle\\", "
                                     "\\"square\\" or \\"indented triangle\\".");
}}

}}  // namespace maze_sprites
#endif
''')
    Path(out).write_text(''.join(parts), encoding='utf-8')
    print('wrote', out)


if __name__ == '__main__':
    PY_DIR = Path(sys.argv[2])
    main(sys.argv[1])
